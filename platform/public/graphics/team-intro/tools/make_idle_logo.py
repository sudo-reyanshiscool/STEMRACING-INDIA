#!/usr/bin/env python3
"""Builds assets/brand/rf-idle-logo.js from the official idle logo page, so the holding screen can show
the Regional Finals logo with its gradient travelling round the SR mark.
It drops the logo page's black backing and renames its outer id so it cannot clash with the screen.
Run from the team-intro folder:  python3 tools/make_idle_logo.py"""
import json, os, re
here = os.path.dirname(os.path.abspath(__file__))
LOGO = os.path.expanduser("~/Documents/STEM Racing/India Official/STEM Racing Regional Finals India_Idle.html")
LAP = 24  # seconds for the gradient to go once round the mark
page = open(LOGO, encoding="utf-8").read()
svg = page[page.index("<svg"):page.index("</svg>") + 6]
svg, n = re.subn(r'<rect x="-10" y="-60" width="1200" height="700" fill="#000"/>\s*', "", svg, count=1)
assert n == 1, "black backing rect not found - the logo file has changed"
assert svg.count('id="stage"') == 1
svg = svg.replace('id="stage"', 'id="rf-idle-logo"')
script = page[page.index("<script"):page.index("</script>")]
script = script[script.index(">") + 1:]
old = script[script.index("if(!/[?&]capture/"):script.rindex("})();")]
assert "requestAnimationFrame(loop)" in old, "logo loop not found - the logo file has changed"
new = """let ph=0,last=null; window.seek(0);
const still=matchMedia('(prefers-reduced-motion: reduce)').matches;
const loop=ts=>{const dt=last===null?0:Math.min(.1,(ts-last)/1000); last=ts;
  if(!still&&host.offsetParent!==null&&host.closest('.scene.on')){ph+=dt/%d; window.seek((ph%%1)*DUR);}
  requestAnimationFrame(loop);};
requestAnimationFrame(loop);
""" % LAP
script = script.replace(old, new)
out = """// Generated by tools/make_idle_logo.py from the official idle logo page. Do not edit by hand.
window.SRIdleLogo={mount:function(host){host.innerHTML=%s;
%s
}};
""" % (json.dumps(svg), script)
assert "</script" not in out
open(os.path.join(here, "..", "assets", "brand", "rf-idle-logo.js"), "w", encoding="utf-8").write(out)
print("wrote assets/brand/rf-idle-logo.js", len(out))
