/* STEM Racing animated backgrounds.
   The nine official gradient files, flowing in a seamless loop (60 s by default).

   Use:
     load ../shared/sr-background.js with a script tag, then:
     const bg = SRBackground.mount(element, 'sr', { darken: 0.4 });
     bg.set('hot');        // switch gradient
     bg.darken(0.6);       // 0 = as supplied, 1 = black
     bg.destroy();

   Names: sr, blue, cold, blue-green, green, full-range, hot, pink-orange, orange-yellow.
   The element must be positioned (relative/absolute); the background sits behind its content.
   Generated by build_background.py – edit sr-background.src.js, not sr-background.js. */
(function () {
  const SETS = {
/*__SETS__*/
  };
  const VS = 'attribute vec2 a;varying vec2 v;void main(){v=a*.5+.5;gl_Position=vec4(a,0.,1.);}';
  const FS = `precision highp float;uniform sampler2D u_tex;uniform float u_t;uniform float u_rot;uniform float u_dark;varying vec2 v;
void main(){vec2 p=v;float t=u_t;vec2 q=p;
q+=0.10*vec2(sin(p.y*4.0+4.0*t)+sin(p.x*2.5-3.0*t+1.3),cos(p.x*3.5-5.0*t)+cos(p.y*2.0+4.0*t+2.1));
q+=0.06*vec2(sin(q.y*7.0-7.0*t+0.7),cos(q.x*6.0+6.0*t+4.0));
q=(q-0.5)*0.62+0.5;
if(u_rot>0.5)q=vec2(q.y,1.0-q.x);
vec3 c=texture2D(u_tex,clamp(q,0.002,0.998)).rgb;
gl_FragColor=vec4(mix(c,vec3(0.0196,0.0,0.0431),u_dark),1.0);}`;
  const views = new Set();
  let running = false;
  const still = window.matchMedia && matchMedia('(prefers-reduced-motion: reduce)').matches;
  function frame() {
    if (!views.size) { running = false; return; }
    const now = performance.now() / 1000;
    views.forEach(v => v.draw(now));
    requestAnimationFrame(frame);
  }
  function mount(el, name, opts) {
    opts = opts || {};
    const loop = opts.loop || 60;
    let dark = opts.darken || 0, current = null, ready = false, tex = null;
    const cv = document.createElement('canvas');
    cv.width = opts.width || 960; cv.height = opts.height || 540;
    cv.style.cssText = 'position:absolute;inset:0;width:100%;height:100%;display:block;z-index:-1;pointer-events:none';
    cv.setAttribute('aria-hidden', 'true');
    if (getComputedStyle(el).position === 'static') el.style.position = 'relative';
    el.style.isolation = 'isolate';
    el.insertBefore(cv, el.firstChild);
    const gl = cv.getContext('webgl', { antialias: false, alpha: false });
    let ut, ur, ud;
    if (gl) {
      const sh = (type, src) => { const o = gl.createShader(type); gl.shaderSource(o, src); gl.compileShader(o); return o; };
      const pr = gl.createProgram();
      gl.attachShader(pr, sh(gl.VERTEX_SHADER, VS)); gl.attachShader(pr, sh(gl.FRAGMENT_SHADER, FS)); gl.linkProgram(pr); gl.useProgram(pr);
      gl.bindBuffer(gl.ARRAY_BUFFER, gl.createBuffer());
      gl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1, -1, 1, -1, -1, 1, 1, 1]), gl.STATIC_DRAW);
      const loc = gl.getAttribLocation(pr, 'a'); gl.enableVertexAttribArray(loc); gl.vertexAttribPointer(loc, 2, gl.FLOAT, false, 0, 0);
      ut = gl.getUniformLocation(pr, 'u_t'); ur = gl.getUniformLocation(pr, 'u_rot'); ud = gl.getUniformLocation(pr, 'u_dark');
      tex = gl.createTexture();
    }
    const view = {
      draw(now) {
        if (!gl || !ready) return;
        gl.uniform1f(ut, (still ? 0 : (now % loop) / loop) * Math.PI * 2);
        gl.uniform1f(ud, dark);
        gl.drawArrays(gl.TRIANGLE_STRIP, 0, 4);
      }
    };
    function set(n) {
      const s = SETS[n] || SETS.sr; current = SETS[n] ? n : 'sr';
      if (!gl) {  // no WebGL: show the still gradient
        cv.style.display = 'none';
        el.style.background = 'linear-gradient(rgba(5,0,11,' + dark + '),rgba(5,0,11,' + dark + ')),url(' + s.src + ') center/cover';
        return;
      }
      const img = new Image(), want = current;
      img.onload = () => {
        if (want !== current) return;
        gl.bindTexture(gl.TEXTURE_2D, tex); gl.pixelStorei(gl.UNPACK_FLIP_Y_WEBGL, true);
        gl.texImage2D(gl.TEXTURE_2D, 0, gl.RGB, gl.RGB, gl.UNSIGNED_BYTE, img);
        gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MIN_FILTER, gl.LINEAR); gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_MAG_FILTER, gl.LINEAR);
        gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_S, gl.CLAMP_TO_EDGE); gl.texParameteri(gl.TEXTURE_2D, gl.TEXTURE_WRAP_T, gl.CLAMP_TO_EDGE);
        gl.uniform1f(ur, s.rot); ready = true; view.draw(performance.now() / 1000);
      };
      img.src = s.src;
    }
    set(name);
    views.add(view);
    if (!running) { running = true; requestAnimationFrame(frame); }
    return {
      set,
      darken(d) { dark = Math.max(0, Math.min(1, d)); if (!gl) set(current); },
      get name() { return current; },
      destroy() { views.delete(view); cv.remove(); }
    };
  }
  window.SRBackground = { mount, names: Object.keys(SETS) };
})();
